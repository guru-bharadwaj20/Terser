"""Row **5.1.7** feature feedback: the share of the prompt's information a rewrite removes.

Row 5.1.6 ranks ``sum_si_removed`` first by permutation importance and |SHAP|. The raw sum grows
with prompt length, so long prompts look risky even when the rewrite removes a small part of
them. :mod:`terser.features.pair` now emits ``si_removed_share = sum_si_removed / total
self-information of the original``. On the existing row 3.1.3 table the denominator is
``prompt_mean_si * prompt_words`` (same tokens, same GPT-2 surprisal), so the feature is added
here without recomputing surprisal. LightGBM (the row 5.1.5 best configuration) is scored with
and without it under the grouped protocol, 5 seeds.

CLI::

    python -m terser.phase5.feature_feedback
"""

from __future__ import annotations

import argparse
import json
from collections.abc import Sequence
from pathlib import Path

import numpy as np
import pandas as pd

from terser.eval.curves import roc_auc
from terser.eval.cv import out_of_fold_scores

__all__ = ["main"]


def _lgbm(seed: int):  # type: ignore[no-untyped-def]
    import lightgbm as lgb

    def fp(X: np.ndarray, y: np.ndarray, Xv: np.ndarray) -> np.ndarray:
        m = lgb.LGBMClassifier(
            learning_rate=0.1, n_estimators=70, max_depth=3, random_state=seed, verbose=-1
        )
        return np.asarray(m.fit(X, y).predict_proba(Xv)[:, 1])

    return fp


def main(argv: Sequence[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Row 5.1.7 feature feedback.")
    ap.add_argument("--table", type=Path, default=Path("data/processed/p4_pairs.parquet"))
    ap.add_argument("--out", type=Path, default=Path("reports/p5_feature_feedback.md"))
    ap.add_argument("--seeds", type=int, default=5)
    args = ap.parse_args(argv)
    df = pd.read_parquet(args.table)
    total = df.prompt_mean_si * df.prompt_words
    df["si_removed_share"] = np.where(total > 0, df.sum_si_removed / total, 0.0)
    y = df.label.to_numpy()
    cats, groups = df.category.astype(str).tolist(), df.group.astype(str).tolist()
    base = [c for c in df.columns if c not in ("id", "group", "category", "label")]
    base.remove("si_removed_share")
    rows = []
    for name, cols in (("without", base), ("with si_removed_share", [*base, "si_removed_share"])):
        X = df[cols].to_numpy(np.float64)
        aucs = [
            roc_auc(y, out_of_fold_scores(_lgbm(s), X, y, cats, groups, seed=s).scores)
            for s in range(args.seeds)
        ]
        rows.append({"features": name, "auc": float(np.mean(aucs)), "sd": float(np.std(aucs))})
    gain = rows[1]["auc"] - rows[0]["auc"]
    corr = float(np.corrcoef(df.si_removed_share, y)[0, 1])
    text = (
        "# Feature feedback (row 5.1.7)\n\n"
        "Generated by `python -m terser.phase5.feature_feedback`. Finding (row 5.1.6): "
        "`sum_si_removed` is the most important feature. The new feature `si_removed_share` "
        "(added to `terser.features.pair.PAIR_FEATURES`) normalises it by the prompt's total "
        "self-information.\n\n"
        "| features | grouped OOF AUC (LightGBM, 5 seeds) |\n|---|---|\n"
        + "".join(f"| {r['features']} | {r['auc']:.4f} ± {r['sd']:.4f} |\n" for r in rows)
        + f"\nChange: **{gain:+.4f}** AUC. Point-biserial correlation of `si_removed_share` with "
        f"`degraded`: {corr:.3f}.\n"
    )
    args.out.write_text(text, encoding="utf-8")
    print(json.dumps({"rows": rows, "gain": gain, "corr": corr}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
