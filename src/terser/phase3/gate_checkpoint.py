"""Checkpoint **C3.3**: the best classical quality gate (Tree / LR / KNN).

C3.3 asks for grouped-OOF ROC-AUC **>= 0.75** and specificity **>= 0.40** at sensitivity 0.95.
The grid reports (rows 3.3.x, 3.4.2, 3.5.1) give AUC only; this scores the best configuration of
each family from those grids on both criteria, with the row 3.2.4 grouped 5-fold protocol and
the operating point of :func:`terser.eval.threshold.choose_threshold` (maximise specificity
subject to sensitivity >= 0.95) fitted on the out-of-fold scores of each seed.

CLI::

    python -m terser.phase3.gate_checkpoint
"""

from __future__ import annotations

import argparse
import json
from collections.abc import Sequence
from pathlib import Path
from typing import Any

import numpy as np

from terser.eval.baselines import BASELINES
from terser.eval.cv import out_of_fold_scores
from terser.eval.threshold import choose_threshold
from terser.phase3.studies import FitPredict, knn_fp, load_table, lr_fp, safe_auc, tree_fp

__all__ = ["CANDIDATES", "main"]

# Best configuration per family in the committed grids (p3_tree_pruning.md, p3_lr_grid.md,
# p3_knn_grid.md), plus the next k for KNN since AUC was still rising at k = 25.
CANDIDATES: dict[str, FitPredict] = {
    "Tree (C4.5, depth 8, min leaf 50)": tree_fp(8, 50),
    "Tree (C4.5, depth 4, min leaf 10)": tree_fp(4, 10),
    "LR (l2, C = 1)": lr_fp("l2", 1.0),
    "KNN (k = 25, manhattan, distance)": knn_fp(25, "manhattan", "distance"),
    "KNN (k = 51, manhattan, distance)": knn_fp(51, "manhattan", "distance"),
}


def main(argv: Sequence[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="C3.3 quality-gate checkpoint.")
    ap.add_argument("--data", type=Path, default=Path("data/processed/pair_features.parquet"))
    ap.add_argument("--out", type=Path, default=Path("reports/p3_gate_checkpoint.md"))
    ap.add_argument("--seeds", type=int, nargs="+", default=[0, 1, 2])
    args = ap.parse_args(argv)
    data = load_table(args.data)
    rows: list[dict[str, Any]] = []
    baselines = {f"baseline: {k}": make() for k, make in BASELINES.items()}
    for name, fp in {**CANDIDATES, **baselines}.items():
        aucs, specs = [], []
        for s in args.seeds:
            oof = out_of_fold_scores(fp, data.X, data.y, data.categories, data.groups, seed=s)
            aucs.append(safe_auc(data.y, oof.scores))
            specs.append(choose_threshold(data.y, oof.scores, 0.95).specificity)
        rows.append(
            {
                "model": name,
                "auc": float(np.mean(aucs)),
                "auc_sd": float(np.std(aucs)),
                "spec": float(np.mean(specs)),
                "spec_sd": float(np.std(specs)),
            }
        )
        print(json.dumps(rows[-1]), flush=True)
    # The gate is chosen on both criteria: a model counts if it meets the AUC floor *and* the
    # specificity floor at the operating point; the highest-AUC model is reported either way.
    models = [r for r in rows if not r["model"].startswith("baseline")]
    top_auc = max(models, key=lambda r: r["auc"])
    passing = [r for r in models if r["auc"] >= 0.75 and r["spec"] >= 0.40]
    ok = bool(passing)
    best = max(passing, key=lambda r: r["spec"]) if passing else top_auc
    table = "\n".join(
        f"| {r['model']} | {r['auc']:.3f} ± {r['auc_sd']:.3f} | "
        f"{r['spec']:.3f} ± {r['spec_sd']:.3f} |"
        for r in rows
    )
    text = (
        "# C3.3 quality gate (best of Tree / LR / KNN)\n\n"
        f"Generated by `python -m terser.phase3.gate_checkpoint`. `{data.source}` "
        f"(sha256 {data.sha256}), {len(data.y):,} pairs, {len(set(data.groups)):,} source "
        f"prompts, seeds {', '.join(map(str, args.seeds))}. Grouped stratified 5-fold "
        "out-of-fold scores (row 3.2.4); the specificity is at the threshold that maximises "
        "specificity subject to sensitivity >= 0.95 on each seed's out-of-fold scores.\n\n"
        "| model | ROC-AUC | specificity at sensitivity 0.95 |\n|---|---|---|\n"
        f"{table}\n\n"
        f"Chosen gate: **{best['model']}**, AUC {best['auc']:.3f} (target >= 0.75), "
        f"specificity {best['spec']:.3f} at sensitivity 0.95 (target >= 0.40). "
        f"{len(passing)} of {len(models)} models meet both targets. The highest-AUC model, "
        f"{top_auc['model']} ({top_auc['auc']:.3f}), reaches only {top_auc['spec']:.3f} "
        "specificity, so overall ranking (AUC) and the high-sensitivity operating point pick "
        "different models; the gate is used at that operating point. "
        f"C3.3: **{'pass' if ok else 'fail'}**.\n"
    )
    args.out.write_text(text, encoding="utf-8")
    print(json.dumps({"best": best["model"], "auc": best["auc"], "spec": best["spec"], "ok": ok}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
