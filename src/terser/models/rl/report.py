"""RL vs SFT val report (stretch S-9.3, row **9.3.5**, check **C9.3**).

The same val table as C8.3 (:func:`terser.models.rewriter.val_report.rung_metrics`) for the GRPO
rewriter next to its SFT starting point, plus:

* **C9.3 (no reward hacking):** precision of the served quality gate on each rung's val rewrites,
  i.e. the judged-preserved share of the (rewrite, target) pairs whose non-fallback rewrite the
  gate passes (``P(degraded) <= gate_threshold``). Its Phase 2 precision is
  ``1 - degraded_share_passed`` at the deployed operating point in ``reports/p11_fast_path.json``
  (grouped OOF on the 14,732 labelled Phase 2 train pairs). Pass when the RL precision is within
  5 pp of it. A Wilson 95% interval is shown because few rewrites may pass the gate.
* degenerate-output rate of the val rewrites (:func:`terser.models.rl.grpo.degenerate_kind`) and
  the C9.5 comparison, for information (C9.4 needs 1,000 samples; the val split has 285).

Entry point::

    python -m terser.models.rl.report --rung hpo08=... --rung grpo=... --rl grpo --sft hpo08 \
        --labels val_labels_p93.jsonl --out reports/p9_rl_vs_sft.md
"""

from __future__ import annotations

import argparse
import json
import math
from collections.abc import Callable, Sequence
from pathlib import Path
from typing import Any

from terser.models.rewriter.val_report import rung_metrics
from terser.models.rl.grpo import degenerate_kind

__all__ = ["gate_precision", "main", "wilson"]

Row = dict[str, Any]
TOLERANCE = 0.05


def wilson(k: int, n: int, z: float = 1.96) -> tuple[float, float]:
    if n == 0:
        return 0.0, 1.0
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return max(0.0, c - h), min(1.0, c + h)


def gate_precision(
    rewrites: Sequence[Row], scores: Sequence[float], labels: Sequence[Row], tag: str, thr: float
) -> dict[str, Any]:
    """Judged-preserved share of gate-passed (rewrite, target) pairs of rung ``tag``."""
    ok: dict[tuple[str, str], bool] = {}
    for r in labels:
        pid, _, t = r["candidate_id"].rpartition(":")
        if t == tag:
            ok[(pid, r["target"])] = r["label"] == "preserved"
    targets = sorted({t for _, t in ok})
    passed = [w for w, s in zip(rewrites, scores, strict=True) if not w["fell_back"] and s <= thr]
    ys = [ok[(w["id"], t)] for w in passed for t in targets if (w["id"], t) in ok]
    k, n = sum(ys), len(ys)
    lo, hi = wilson(k, n)
    return {
        "rewrites": len(rewrites),
        "gate_passed": len(passed),
        "pairs": n,
        "preserved": k,
        "precision": k / n if n else None,
        "ci95": [lo, hi],
    }


def _jsonl(path: Path) -> list[Row]:
    return [json.loads(x) for x in path.read_text(encoding="utf-8").splitlines() if x.strip()]


def _fmt(x: float | None) -> str:
    return "-" if x is None else f"{x:.1%}"


def build(
    rungs: dict[str, list[Row]],
    labels: list[Row],
    rl: str,
    sft: str,
    score: Callable[[list[Row]], list[float]],
    thr: float,
    p2_precision: float,
    training: Row | None = None,
    audit_md: str | None = None,
) -> tuple[str, Row]:
    res: Row = {"rungs": {}, "gate_threshold": thr, "phase2_precision": p2_precision}
    for tag, rows in rungs.items():
        m = rung_metrics(rows, labels, tag)
        m["gate"] = gate_precision(rows, score(rows), labels, tag, thr)
        kinds = [degenerate_kind(str(w.get("raw_rewrite", w["rewrite"])), False) for w in rows]
        m["degenerate_rate"] = sum(k is not None for k in kinds) / max(len(kinds), 1)
        res["rungs"][tag] = m
    g = res["rungs"][rl]["gate"]
    prec = g["precision"]
    res["c9_3"] = prec is not None and abs(prec - p2_precision) <= TOLERANCE
    a, b = res["rungs"][rl], res["rungs"][sft]
    cat_drop = max(
        (b["preserved_by_category"][c] - a["preserved_by_category"].get(c, 0.0))
        for c in b["preserved_by_category"]
    )
    res["c9_5"] = (
        a["median_savings"] >= b["median_savings"] + 0.03
        and b["preserved"] - a["preserved"] <= 0.01
        and cat_drop <= 0.02
    )
    L = [
        "# RL vs SFT rewriter on the val split (stretch S-9.3, row 9.3.5, check C9.3)",
        "",
        "Generated by `python -m terser.models.rl.report`. Same val table as C8.3"
        " (`reports/p8_rewriter_val.md`): val split (285 prompts), greedy decoding, 8.3.7"
        " safeguard on, savings on the Qwen2.5 tokenizer, preservation judged by"
        " Qwen2.5-32B-Instruct-AWQ (`pairwise_avg`) on both targets; fallbacks count as preserved."
        f" `{rl}` is the GRPO policy, `{sft}` its SFT starting point (and KL reference).",
        "",
        "| Rung | n | Median savings | Oracle median | Fell back | Preserved | Latency (s)"
        " | C8.3 |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for tag, m in res["rungs"].items():
        L.append(
            f"| {tag} | {m['n']} | {m['median_savings']:.1%} | {m['oracle_median_savings']:.1%} "
            f"| {m['fell_back']} | {m['preserved']:.1%} | {m['latency_s']:.2f} "
            f"| {'pass' if m['c8_3'] else 'fail'} |"
        )
    cats = sorted({c for m in res["rungs"].values() for c in m["preserved_by_category"]})
    L += ["", "Preservation by category:", "", "| Rung | " + " | ".join(cats) + " |"]
    L.append("|---" * (len(cats) + 1) + "|")
    for tag, m in res["rungs"].items():
        pc = m["preserved_by_category"]
        L.append(f"| {tag} | " + " | ".join(f"{pc.get(c, 0):.1%}" for c in cats) + " |")
    L += [
        "",
        "## C9.3: gate precision (no reward hacking)",
        "",
        f"Gate: `models/fast/gate.onnx` at the served threshold {thr} (rejects P(degraded) >"
        " threshold). Precision = judged-preserved share of the (rewrite, target) pairs whose"
        f" non-fallback rewrite the gate passes. Phase 2 precision: **{p2_precision:.1%}**"
        " (1 - degraded share among passed, grouped OOF on the Phase 2 train pairs,"
        " `reports/p11_fast_path.json`).",
        "",
        "| Rung | Gate-passed rewrites | Judged pairs | Precision | Wilson 95% CI | vs Phase 2 |",
        "|---|---|---|---|---|---|",
    ]
    for tag, m in res["rungs"].items():
        gg = m["gate"]
        diff = (
            "-" if gg["precision"] is None else f"{(gg['precision'] - p2_precision) * 100:+.1f} pp"
        )
        L.append(
            f"| {tag} | {gg['gate_passed']} / {gg['rewrites']} | {gg['pairs']} "
            f"| {_fmt(gg['precision'])} | {gg['ci95'][0]:.1%}-{gg['ci95'][1]:.1%} | {diff} |"
        )
    verdict = "pass" if res["c9_3"] else "fail"
    if prec is None:
        why = "no RL rewrite passes the gate, so its precision is undefined"
    else:
        why = (
            f"RL precision {prec:.1%} vs Phase 2 {p2_precision:.1%}, "
            f"|diff| = {abs(prec - p2_precision) * 100:.1f} pp (limit 5 pp)"
        )
    L += ["", f"**C9.3: {verdict}** ({why})."]
    if prec is not None and g["pairs"] < 100:
        L.append(
            f"Caveat: only {g['pairs']} judged pairs pass the gate, so the interval is wide"
            f" ({g['ci95'][0]:.1%}-{g['ci95'][1]:.1%})."
        )
    L += [
        "",
        "## Other S-9.3 checks (information; not flipped here)",
        "",
        f"* Degenerate val rewrites (empty / non-natural-language raw output): `{rl}`"
        f" {a['degenerate_rate']:.1%}, `{sft}` {b['degenerate_rate']:.1%}. C9.4 needs 1,000"
        " samples; the training-time monitor (`degenerate_*` metrics) covers that.",
        f"* C9.5 (savings >= SFT + 3 pp, preservation not lower by > 1 pp overall or > 2 pp in"
        f" any category): {'pass' if res['c9_5'] else 'fail'} (savings"
        f" {(a['median_savings'] - b['median_savings']) * 100:+.1f} pp, preservation"
        f" {(a['preserved'] - b['preserved']) * 100:+.1f} pp, worst category drop"
        f" {cat_drop * 100:.1f} pp)." + ("" if res["c9_5"] else " SFT stays champion."),
    ]
    if training:
        L += ["", "## Training", ""] + [f"* {k}: {v}" for k, v in training.items()]
    if audit_md:
        L += ["", "## Reward-hacking audit (row 9.3.3)", "", audit_md.strip()]
    return "\n".join(L) + "\n", res


def main(argv: Sequence[str] | None = None) -> int:  # pragma: no cover - needs gate.onnx + labels
    ap = argparse.ArgumentParser(description="RL vs SFT val report (row 9.3.5, C9.3).")
    ap.add_argument("--rung", action="append", required=True, help="tag=path to generate output")
    ap.add_argument("--labels", type=Path, nargs="+", required=True)
    ap.add_argument("--rl", required=True)
    ap.add_argument("--sft", required=True)
    ap.add_argument("--fast-path-report", type=Path, default=Path("reports/p11_fast_path.json"))
    ap.add_argument("--training", type=Path, default=None, help="GRPO summary.json")
    ap.add_argument("--audit-md", type=Path, default=None)
    ap.add_argument("--out", type=Path, default=Path("reports/p9_rl_vs_sft.md"))
    args = ap.parse_args(argv)

    from terser.phase10.rewriter_hpo import GateScorer, gate_threshold

    labels = [r for p in args.labels for r in _jsonl(p)]
    rungs = {}
    for spec in args.rung:
        tag, _, path = spec.partition("=")
        rungs[tag] = _jsonl(Path(path))
    fp = json.loads(args.fast_path_report.read_text(encoding="utf-8"))
    p2 = 1 - float(fp["operating_point"]["chosen"]["degraded_share_passed"])
    training = None
    if args.training and args.training.exists():
        s = json.loads(args.training.read_text(encoding="utf-8"))
        first, last = s.get("first") or {}, s.get("last") or {}
        training = {
            "start": f"`{s.get('init_adapter')}` merged into `{s.get('model')}`",
            "steps done": s.get("steps_done"),
            "reward (step 1 -> last)": f"{first.get('reward_mean', 0):.2f} ->"
            f" {last.get('reward_mean', 0):.2f}",
            "gate pass rate (step 1 -> last)": f"{first.get('gate_pass_rate', 0):.1%} ->"
            f" {last.get('gate_pass_rate', 0):.1%}",
            "KL to SFT (last)": f"{last.get('kl', 0):.4f}",
            "degenerate rate (last step)": f"{last.get('degenerate_any', 0):.1%}",
        }
    audit = args.audit_md.read_text(encoding="utf-8") if args.audit_md else None
    if audit:
        audit = "\n".join(x for x in audit.splitlines() if not x.startswith("# "))
    md, res = build(
        rungs, labels, args.rl, args.sft, GateScorer(), gate_threshold(), p2, training, audit
    )
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(md, encoding="utf-8")
    args.out.with_suffix(".json").write_text(json.dumps(res, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({"c9_3": res["c9_3"], "c9_5": res["c9_5"]}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
