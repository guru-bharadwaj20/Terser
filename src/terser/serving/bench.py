"""Cold vs warm-hit latency of the rewrite service cache (row 11.3.4).

Runs every fixture prompt through :class:`RewriteService` (fast path, real ``gpt-4o`` tokenizer)
once cold, then ``repeats`` times warm, and writes percentiles to JSON and Markdown::

    python -m terser.serving.bench --out reports/p11_cache_latency

Latency here is in-process service time (no HTTP); tokenizers are loaded before timing starts.
"""

from __future__ import annotations

import argparse
import json
import platform
import time
from collections.abc import Sequence
from pathlib import Path
from typing import Any

import numpy as np

from terser.config import project_root
from terser.serving.accounting import Pricing
from terser.serving.service import RewriteService

# Default prompt set for the load test (20 hand-written samples, also used by the tests); pass
# --prompts for real traffic.
FIXTURE = project_root() / "data" / "samples" / "casual_prompts.jsonl"


def _pct(xs: Sequence[float]) -> dict[str, float]:
    a = np.asarray(xs)
    return {
        "n": int(a.size),
        "p50_ms": float(np.percentile(a, 50)),
        "p95_ms": float(np.percentile(a, 95)),
        "p99_ms": float(np.percentile(a, 99)),
        "mean_ms": float(a.mean()),
    }


def run(prompts: Sequence[str], target: str = "gpt-4o", repeats: int = 50) -> dict[str, Any]:
    """Measure cold (miss) and warm (hit) latency in milliseconds."""
    svc = RewriteService(pricing=Pricing({target: 0.0}))
    svc.features("warm up the tokenizer", target)
    cold, warm = [], []
    for p in prompts:
        t0 = time.perf_counter()
        r = svc.rewrite(p, target)
        cold.append((time.perf_counter() - t0) * 1e3)
        assert not r.cached
    for _ in range(repeats):
        for p in prompts:
            t0 = time.perf_counter()
            r = svc.rewrite(p, target)
            warm.append((time.perf_counter() - t0) * 1e3)
            assert r.cached
    return {
        "target": target,
        "prompts": len(prompts),
        "repeats": repeats,
        "cold": _pct(cold),
        "warm_hit": _pct(warm),
        "speedup_p50": _pct(cold)["p50_ms"] / _pct(warm)["p50_ms"],
        "host": {"platform": platform.platform(), "python": platform.python_version()},
    }


def main(argv: Sequence[str] | None = None) -> int:
    from terser.tracking.runs import get_git_sha

    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", type=Path, required=True, help="output stem (.json and .md)")
    ap.add_argument("--repeats", type=int, default=50)
    ap.add_argument("--prompts", type=Path, default=FIXTURE, help="JSONL with a prompt field")
    args = ap.parse_args(argv)
    lines = args.prompts.read_text(encoding="utf-8").split("\n")
    prompts = [json.loads(x)["prompt"] for x in lines if x]
    res = run(prompts, repeats=args.repeats)
    res["git_sha"] = get_git_sha()
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.with_suffix(".json").write_text(json.dumps(res, indent=2) + "\n", encoding="utf-8")
    c, w = res["cold"], res["warm_hit"]
    md = [
        "# P11 cache latency: cold vs warm hit (row 11.3.4)",
        "",
        f"Generated by `python -m terser.serving.bench --out {args.out.as_posix()}` on top of git "
        f"`{res['git_sha'][:12]}` on `{res['host']['platform']}`, Python "
        f"{res['host']['python']}. In-process service latency (fast path, target "
        f"`{res['target']}`, no HTTP), {res['prompts']} fixture prompts, "
        f"{res['repeats']} warm repeats each.",
        "",
        "| Request | n | p50 (ms) | p95 (ms) | p99 (ms) | mean (ms) |",
        "| :--- | ---: | ---: | ---: | ---: | ---: |",
        f"| Cold (miss) | {c['n']} | {c['p50_ms']:.3f} | {c['p95_ms']:.3f} | "
        f"{c['p99_ms']:.3f} | {c['mean_ms']:.3f} |",
        f"| Warm hit | {w['n']} | {w['p50_ms']:.4f} | {w['p95_ms']:.4f} | "
        f"{w['p99_ms']:.4f} | {w['mean_ms']:.4f} |",
        "",
        f"Median speed-up of a hit over a miss: **{res['speedup_p50']:.0f}x**. A hit skips "
        "rewriting, feature extraction, tokenisation and gating; it still hashes the normalised "
        "prompt and logs the request (Prometheus metrics are off in this run). These are "
        "single-host CPU numbers, not "
        "the C11.2 load test (p95 at 20 RPS over HTTP).",
        "",
    ]
    args.out.with_suffix(".md").write_text("\n".join(md), encoding="utf-8")
    print("\n".join(md))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
