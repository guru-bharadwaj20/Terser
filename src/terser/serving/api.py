"""FastAPI app: ``POST /rewrite``, ``GET /metrics``, ``GET /healthz`` (rows 11.3.1, 11.5.1).

Run::

    uvicorn terser.serving.api:app --host 0.0.0.0 --port 8080
    # interactive OpenAPI docs at http://localhost:8080/docs, schema at /openapi.json

Configuration comes from ``configs/serving/default.yaml`` (override with
``TERSER_SERVING_CONFIG``). The request/response schema and worked examples are in
``docs/serving/api.md``; ``docs/serving/openapi.json`` is generated by
``python -m terser.serving.api --openapi docs/serving/openapi.json``.
"""

from __future__ import annotations

import argparse
import json
import os
from collections.abc import Sequence
from pathlib import Path
from typing import Any, Literal

import yaml
from fastapi import FastAPI, HTTPException, Response
from pydantic import BaseModel, ConfigDict, Field

from terser.serving.accounting import Pricing
from terser.serving.metrics import ServiceMetrics
from terser.serving.paths import Gate, OnnxGate, OpenAICompatibleRewriter
from terser.serving.service import RewriteService

__all__ = ["RewriteIn", "RewriteOut", "app", "build_service", "create_app", "load_config"]

DEFAULT_CONFIG = Path(__file__).resolve().parents[3] / "configs" / "serving" / "default.yaml"

EXAMPLE_PROMPT = (
    "hey so um, could you maybe write a Python function that checks if a string is a "
    "palindrome? It should ignore case. Thanks so much!!"
)


class RewriteIn(BaseModel):
    """``POST /rewrite`` request body."""

    model_config = ConfigDict(
        json_schema_extra={
            "examples": [{"prompt": EXAMPLE_PROMPT, "target": "gpt-4o", "mode": "fast"}]
        }
    )

    prompt: str = Field(..., min_length=1, max_length=32_000, description="The casual prompt")
    target: str = Field("gpt-4o", description="Target model; selects the tokenizer and price")
    mode: Literal["fast", "quality"] = Field(
        "fast", description="fast = CPU span path; quality = generative rewriter with fallback"
    )
    consent_raw_text: bool = Field(
        False, description="Allow raw prompt/rewrite text in logs (hashes only otherwise)"
    )


class RewriteOut(BaseModel):
    """``POST /rewrite`` response body."""

    model_config = ConfigDict(
        json_schema_extra={
            "examples": [
                {
                    "rewrite": "Write a Python function that checks if a string is a "
                    "palindrome. It should ignore case.",
                    "tokens_before": 29,
                    "tokens_after": 18,
                    "gate_score": 0.0,
                    "fallback_used": False,
                    "path": "fast",
                    "mode": "fast",
                    "target": "gpt-4o",
                    "gate_rejected": False,
                    "fallback_reason": None,
                    "cached": False,
                    "net_savings_usd": 2.75e-05,
                    "request_id": "3f2b0c9e1d4a4b7f8e6a5c2d1b0a9f8e",
                    "latency_ms": 3.1,
                }
            ]
        }
    )

    rewrite: str
    tokens_before: int
    tokens_after: int
    gate_score: float = Field(..., description="Gate P(degraded) of the candidate rewrite")
    fallback_used: bool
    path: Literal["fast", "quality", "original"]
    mode: Literal["fast", "quality"]
    target: str
    gate_rejected: bool
    fallback_reason: Literal["timeout", "error", "unavailable", "fast_error"] | None
    cached: bool
    net_savings_usd: float
    request_id: str
    latency_ms: float


def load_config(path: str | Path | None = None) -> dict[str, Any]:
    """Read the serving YAML config."""
    p = Path(path or os.environ.get("TERSER_SERVING_CONFIG") or DEFAULT_CONFIG)
    return dict(yaml.safe_load(p.read_text(encoding="utf-8")))


REPO_ROOT = DEFAULT_CONFIG.parents[2]


def resolve_path(p: str | Path) -> Path:
    """Model paths in a config are relative to the repo root, not the process's cwd."""
    path = Path(p)
    return path if path.is_absolute() else REPO_ROOT / path


def build_service(cfg: dict[str, Any], metrics: ServiceMetrics | None = None) -> RewriteService:
    """Construct the :class:`RewriteService` described by ``cfg``."""
    q = cfg.get("quality") or {}
    quality = None
    if q.get("base_url") and q.get("model"):
        quality = OpenAICompatibleRewriter(
            q["base_url"], q["model"], timeout_s=float(q.get("http_timeout_s", 2.0))
        )
    gate: Gate | None = OnnxGate(resolve_path(cfg["gate_onnx"])) if cfg.get("gate_onnx") else None
    fast = None
    if cfg.get("tagger_onnx"):  # row 11.3.2 ONNX span tagger; else rule-based operators
        from terser.serving.fast_models import OnnxSpanRewriter

        fast = OnnxSpanRewriter(
            resolve_path(cfg["tagger_onnx"]), threshold=float(cfg.get("tagger_threshold", 0.5))
        )
    return RewriteService(
        pricing=Pricing.from_config(cfg["pricing"]),
        fast=fast,
        quality=quality,
        gate=gate,
        gate_threshold=float(cfg.get("gate_threshold", 0.5)),
        quality_timeout_s=float(cfg.get("quality_timeout_s", 0.4)),
        gate_feature_target=cfg.get("gate_feature_target"),
        cache_size=int(cfg.get("cache_size", 10_000)),
        metrics=metrics,
    )


def create_app(service: RewriteService | None = None, metrics: ServiceMetrics | None = None) -> Any:
    """Build the FastAPI app around ``service`` (default: from the config file)."""
    metrics = metrics if metrics is not None else ServiceMetrics()
    svc = service if service is not None else build_service(load_config(), metrics)
    if svc.metrics is None:
        svc.metrics = metrics
    api = FastAPI(
        title="Terser",
        version="0.1.0",
        description="Rewrite casual prompts into token-efficient prompts for a target LLM.",
    )

    @api.post("/rewrite", response_model=RewriteOut, summary="Rewrite a prompt")
    def rewrite(req: RewriteIn) -> RewriteOut:
        try:
            resp = svc.rewrite(
                req.prompt, req.target, req.mode, consent_raw_text=req.consent_raw_text
            )
        except KeyError as exc:
            raise HTTPException(status_code=422, detail=str(exc.args[0])) from exc
        return RewriteOut(**resp.as_dict())

    @api.get("/metrics", summary="Prometheus metrics")
    def prom() -> Response:
        body, ctype = metrics.render()
        return Response(content=body, media_type=ctype)

    @api.get("/healthz", summary="Liveness and path availability")
    def healthz() -> dict[str, Any]:
        return {"status": "ok", "quality_path": svc.quality is not None}

    api.state.service = svc
    return api


class _LazyApp:
    """ASGI app built on first use, so importing this module never loads tokenizers/config."""

    def __init__(self) -> None:
        self._app: Any = None

    async def __call__(self, scope: Any, receive: Any, send: Any) -> None:
        if self._app is None:
            self._app = create_app()
        await self._app(scope, receive, send)


app = _LazyApp()


def main(argv: Sequence[str] | None = None) -> int:
    """``--openapi PATH`` writes the OpenAPI schema."""
    ap = argparse.ArgumentParser()
    ap.add_argument("--openapi", type=Path, required=True)
    args = ap.parse_args(argv)
    svc = RewriteService(pricing=Pricing({"gpt-4o": 0.0}))
    schema = create_app(svc).openapi()
    args.openapi.parent.mkdir(parents=True, exist_ok=True)
    args.openapi.write_text(json.dumps(schema, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {args.openapi}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
