"""Phase 6 clustering studies on the row 6.1 embeddings (rows **6.2**, **6.3**, **6.5**, **6.6**,
**6.8**, **6.9**; checkpoints **C6.1**-**C6.3**).

1. **6.2 / 6.3** - :func:`~terser.models.clustering.analysis.k_sweep` for K-means and bisecting
   K-means over k = 4..30; the chosen k maximises the K-means silhouette (C6.1).
2. **C6.2** - annealed shared-``sigma^2 I`` EM from the K-means centroids; assignment agreement
   with K-means at the smallest ``sigma``.
3. **6.5 / 6.6** - Ward / average / complete agglomerative and divisive trees on a 2,000-prompt
   sample; dendrograms and cophenetic correlations.
4. **6.8** - ARI, NMI and contingency table against the 6 categories.
5. **6.9 / C6.3** - oracle savings and degradation rate per cluster on the labelled train prompts.

Everything goes to ``reports/p6_results.json`` plus the figures and markdown named in the plan.

CLI::

    python -m terser.phase6.studies
"""

from __future__ import annotations

import argparse
import json
from collections.abc import Sequence
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd

from terser.features.embeddings import EmbeddingCache
from terser.models.clustering.analysis import (
    cluster_risk,
    clusters_vs_categories,
    k_sweep,
    plot_k_sweep,
)
from terser.models.clustering.hierarchy import (
    agglomerative_linkage,
    cophenetic_correlation,
    cut_tree,
    divisive_linkage,
)
from terser.models.clustering.kmeans_em import AnnealedSphericalEM, assignment_agreement
from terser.models.clustering.scratch_kmeans import KMeans

__all__ = ["main"]

LINKAGES = ("ward", "average", "complete")


def _jsonl(path: Path) -> list[dict[str, Any]]:
    return [json.loads(x) for x in path.read_text(encoding="utf-8").splitlines() if x.strip()]


def _dendrograms(trees: dict[str, np.ndarray], path: Path) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from scipy.cluster.hierarchy import dendrogram

    fig, axes = plt.subplots(1, len(trees), figsize=(5 * len(trees), 4))
    for ax, (name, Z) in zip(axes, trees.items(), strict=True):
        dendrogram(Z, ax=ax, truncate_mode="lastp", p=30, no_labels=True)
        ax.set_title(name)
    fig.tight_layout()
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, dpi=120)
    plt.close(fig)


def _md_table(df: pd.DataFrame, floatfmt: str = "{:.3f}") -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(map(str, cols)) + " |", "|---" * len(cols) + "|"]
    for r in df.astype(object).itertuples(index=False):
        cells = [floatfmt.format(v) if isinstance(v, float) else str(v) for v in r]
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def render_results(out: dict[str, Any]) -> str:
    """``reports/p6_results.md`` from the ``p6_results.json`` payload."""
    sweep = pd.DataFrame(out["sweep"])
    wide = sweep.pivot(index="k", columns="algorithm", values=["sse", "silhouette", "size_balance"])
    wide.columns = [f"{a}_{m}" for m, a in wide.columns]
    wide = wide.reset_index()[
        [
            "k",
            "kmeans_sse",
            "bisecting_sse",
            "kmeans_silhouette",
            "bisecting_silhouette",
            "kmeans_size_balance",
            "bisecting_size_balance",
        ]
    ]
    em = out["em"]
    cont = pd.DataFrame(out["categories"]["contingency"]).fillna(0).astype(int)
    cont.index.name = "cluster"
    tick = {True: "pass", False: "fail"}
    return "\n".join(
        [
            "# Phase 6 clustering results (rows 6.2, 6.3, 6.5, 6.6, 6.8; C6.1, C6.2)",
            "",
            f"{out['n']:,} train prompts, bge-small 384-d (row 6.1). Generated by "
            "`python -m terser.phase6.studies`; raw numbers in `reports/p6_results.json`.",
            "",
            "## 6.2 / 6.3 K-means vs bisecting K-means",
            "",
            "![k sweep](figures/p6_kmeans_k.png)",
            "",
            _md_table(wide),
            "",
            f"Chosen k = **{out['chosen_k']}** (max K-means silhouette "
            f"{out['silhouette']:.3f}). **C6.1** (silhouette >= 0.10): **{tick[out['c6_1']]}**.",
            "",
            "## C6.2 K-means as the sigma -> 0 limit of EM",
            "",
            "| sigma | agreement with K-means | mean max responsibility |",
            "|---|---|---|",
            *(
                f"| {s} | {a:.4f} | {r:.3f} |"
                for s, a, r in zip(
                    em["sigmas"], em["agreement"], em["mean_max_responsibility"], strict=True
                )
            ),
            "",
            f"**C6.2** (agreement >= 98% at the smallest sigma): **{tick[out['c6_2']]}**.",
            "",
            "## 6.5 / 6.6 Agglomerative vs divisive (2,000-prompt sample)",
            "",
            "![dendrograms](figures/p6_dendrograms.png)",
            "",
            "| tree | cophenetic correlation | ARI vs K-means (cut at k) |",
            "|---|---|---|",
            *(
                f"| {m} | {c:.3f} | {out['tree_vs_kmeans_ari'][m]:.3f} |"
                for m, c in out["cophenetic"].items()
            ),
            "",
            "## 6.8 Clusters vs categories",
            "",
            f"ARI **{out['categories']['ari']:.3f}**, NMI **{out['categories']['nmi']:.3f}**.",
            "",
            _md_table(cont.reset_index()),
            "",
        ]
    )


def main(argv: Sequence[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Phase 6 clustering studies.")
    ap.add_argument("--embeddings", type=Path, default=Path("data/processed/embeddings"))
    ap.add_argument("--name", default="train_bge_small")
    ap.add_argument("--split", type=Path, default=Path("data/processed/splits/train.jsonl"))
    ap.add_argument("--oracle", type=Path, default=Path("data/processed/oracle.csv"))
    ap.add_argument("--labels", type=Path, default=Path("data/processed/labels.jsonl"))
    ap.add_argument("--reports", type=Path, default=Path("reports"))
    ap.add_argument("--k-min", type=int, default=4)
    ap.add_argument("--k-max", type=int, default=30)
    ap.add_argument("--sample", type=int, default=2000)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument(
        "--sigmas",
        type=float,
        nargs="+",
        default=[0.1, 0.05, 0.02, 0.01, 0.005],
        help="EM annealing schedule; start below the collapse temperature of unit embeddings",
    )
    ap.add_argument("--render-only", action="store_true", help="rebuild the markdown from json")
    args = ap.parse_args(argv)

    if args.render_only:
        saved = json.loads((args.reports / "p6_results.json").read_text(encoding="utf-8"))
        (args.reports / "p6_results.md").write_text(render_results(saved), encoding="utf-8")
        return 0
    cache = EmbeddingCache.load(args.embeddings, args.name)
    prompts = {r["id"]: r for r in _jsonl(args.split)}
    ids = [i for i in cache.ids if i in prompts]
    X = cache.get(ids).astype(np.float64)
    figs = args.reports / "figures"
    out: dict[str, Any] = {"n": len(ids)}

    # 6.2 / 6.3 / C6.1
    sweep = k_sweep(X, range(args.k_min, args.k_max + 1), seed=args.seed)
    plot_k_sweep(sweep, figs / "p6_kmeans_k.png")
    km_rows = sweep[sweep.algorithm == "kmeans"]
    k = int(km_rows.loc[km_rows.silhouette.idxmax(), "k"])
    out["sweep"] = sweep.to_dict(orient="records")
    out["chosen_k"] = k
    out["silhouette"] = float(km_rows.silhouette.max())
    out["c6_1"] = out["silhouette"] >= 0.10
    km = KMeans(k, n_init=10, seed=args.seed).fit(X)

    # C6.2
    em = AnnealedSphericalEM(sigmas=tuple(args.sigmas)).fit(X, km.cluster_centers_)
    agree = [assignment_agreement(km.labels_, lab) for lab in em.stage_labels_]
    out["em"] = {
        "sigmas": list(em.sigmas),
        "agreement": agree,
        "mean_max_responsibility": em.stage_max_resp_,
    }
    out["c6_2"] = agree[-1] >= 0.98

    # 6.5 / 6.6
    rng = np.random.default_rng(args.seed)
    idx = np.sort(rng.choice(len(ids), size=min(args.sample, len(ids)), replace=False))
    Xs = X[idx]
    trees = {m: agglomerative_linkage(Xs, m) for m in LINKAGES}
    trees["divisive"] = divisive_linkage(Xs, seed=args.seed)
    _dendrograms(trees, figs / "p6_dendrograms.png")
    out["cophenetic"] = {m: cophenetic_correlation(Z, Xs) for m, Z in trees.items()}
    sample_km = km.labels_[idx]
    out["tree_vs_kmeans_ari"] = {
        m: clusters_vs_categories(cut_tree(Z, k), sample_km)[0] for m, Z in trees.items()
    }

    # 6.8
    cats = [prompts[i]["category"] for i in ids]
    ari, nmi, table = clusters_vs_categories(km.labels_, cats)
    out["categories"] = {"ari": ari, "nmi": nmi, "contingency": table.to_dict()}

    # 6.9 / C6.3
    cluster_of = dict(zip(ids, km.labels_.tolist(), strict=True))
    oracle = pd.read_csv(args.oracle)
    oracle = oracle[~oracle.stand_in]
    sav = oracle.groupby("prompt_id").savings.mean().to_dict()
    recs = [
        r
        for r in _jsonl(args.labels)
        if r.get("split") == "train" and not r.get("stand_in") and r["prompt_id"] in cluster_of
    ]
    risk = cluster_risk(
        [cluster_of[r["prompt_id"]] for r in recs],
        [sav.get(r["prompt_id"], 0.0) for r in recs],
        [float(r["label"] == "degraded") for r in recs],
    )
    out["risk"] = risk.reset_index().to_dict(orient="records")
    out["n_label_records"] = len(recs)
    out["c6_3"] = bool(risk.high_risk.any())

    args.reports.mkdir(parents=True, exist_ok=True)
    (args.reports / "p6_results.json").write_text(
        json.dumps(out, indent=2, default=float) + "\n", encoding="utf-8"
    )
    (args.reports / "p6_results.md").write_text(
        render_results(json.loads(json.dumps(out, default=float))), encoding="utf-8"
    )
    top = table.idxmax(axis=1)
    risk_md = risk.reset_index().assign(
        top_category=lambda d: d.cluster.map(top),
    )
    (args.reports / "p6_cluster_risk.md").write_text(
        "# Phase 6 per-cluster risk (row 6.9, C6.3)\n\n"
        f"K-means k = {k} on {len(ids):,} train prompts (bge-small). Degradation rate over "
        f"{len(recs):,} train label records (both targets); savings = mean oracle savings over "
        "targets. High risk = degradation rate >= 1.5x overall; high-risk clusters become eval "
        "slices in row 12.3.\n\n" + _md_table(risk_md) + "\n",
        encoding="utf-8",
    )
    print(
        json.dumps(
            {
                "k": k,
                "silhouette": out["silhouette"],
                "em_agreement": agree[-1],
                "cophenetic": out["cophenetic"],
                "ari": ari,
                "nmi": nmi,
                "high_risk": int(risk.high_risk.sum()),
            }
        )
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
